#!/usr/bin/env python3
"""Self-host the Sora font and AOS (animate on scroll) for the Windedgesoft site.

What it does (needs an internet connection, run it once):
  1. Downloads the Sora font from Google Fonts as woff2 files -> assets/fonts/
     and writes assets/fonts/fonts.css with local @font-face rules.
  2. Downloads AOS 2.3.4 (aos.css + aos.js) -> assets/vendor/aos/
  3. Rewrites every *.html page in the site folder and assets/css/style.css so
     they use the local files instead of fonts.googleapis.com / jsdelivr.
  4. Removes the unused "Source Sans Pro" font link (style.css only uses Sora).

Everything is downloaded first; pages are only edited if every download worked.
Safe to run again. Your site is a git repo, so `git diff` shows exactly what changed.

Usage:
    python3 selfhost_vendor.py
    python3 selfhost_vendor.py --source /var/www/html/windedgesoft
    python3 selfhost_vendor.py --dry-run
"""

import argparse
import re
import sys
import urllib.error
import urllib.request
from pathlib import Path

DEFAULT_SOURCE = "/var/www/html/windedgesoft"

# Variable-font request: one file per script covers every weight from 300 to 800.
FONT_CSS_URL = "https://fonts.googleapis.com/css2?family=Sora:wght@300..800&display=swap"
# Only these scripts are kept. "latin" covers English and Kiswahili.
KEEP_SUBSETS = ("latin", "latin-ext")

AOS_VERSION = "2.3.4"
AOS_FILES = {
    "aos.css": f"https://cdn.jsdelivr.net/npm/aos@{AOS_VERSION}/dist/aos.css",
    "aos.js": f"https://cdn.jsdelivr.net/npm/aos@{AOS_VERSION}/dist/aos.js",
}

# Google only serves woff2 to modern browsers, so identify as one.
USER_AGENT = (
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/124.0 Safari/537.36"
)


def fetch(url: str) -> bytes:
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            return response.read()
    except (urllib.error.URLError, TimeoutError) as exc:
        raise SystemExit(f"Download failed for {url}\n  {exc}\nNothing was changed.")


def parse_font_faces(css: str):
    """Return [(subset, font_face_block)] from Google's CSS."""
    faces = []
    for match in re.finditer(r"/\*\s*([\w-]+)\s*\*/\s*(@font-face\s*\{.*?\})", css, re.S):
        faces.append((match.group(1), match.group(2)))
    return faces


def build_local_fonts(css: str):
    """Download the woff2 files; return ({filename: bytes}, local_css_text)."""
    files, blocks = {}, []
    for subset, block in parse_font_faces(css):
        if subset not in KEEP_SUBSETS:
            continue
        url_match = re.search(r"url\((https://[^)]+\.woff2)\)", block)
        if not url_match:
            raise SystemExit(f"Unexpected font CSS for subset '{subset}'. Nothing was changed.")
        filename = f"sora-{subset}.woff2"
        files[filename] = fetch(url_match.group(1))
        local = block.replace(url_match.group(0), f"url({filename})")
        blocks.append(f"/* {subset} */\n{local}")
    if not files:
        raise SystemExit("No Sora font files found in Google's response. Nothing was changed.")
    header = "/* Sora (variable, 300-800), self-hosted. Generated by selfhost_vendor.py */\n"
    return files, header + "\n\n".join(blocks) + "\n"


def patch_html(text: str, has_latin: bool) -> str:
    # Drop every Google Fonts link/preconnect (and the "Google Fonts" comment above it)
    text = re.sub(r"\n[ \t]*<!--\s*Google Fonts\s*-->", "", text)
    text = re.sub(r"\n?[ \t]*<link[^>]*fonts\.(?:googleapis|gstatic)\.com[^>]*>", "", text)

    # AOS from the CDN -> local copy
    text = re.sub(r"https://cdn\.jsdelivr\.net/npm/aos@[\d.]+/dist/aos\.css", "assets/vendor/aos/aos.css", text)
    text = re.sub(r"https://cdn\.jsdelivr\.net/npm/aos@[\d.]+/dist/aos\.js", "assets/vendor/aos/aos.js", text)

    # Local font CSS (+ preload so text doesn't flash in a fallback font)
    if "assets/fonts/fonts.css" not in text:
        tag = '<link rel="stylesheet" href="assets/css/style.css">'
        if tag in text:
            extra = ""
            if has_latin:
                extra += ('<link rel="preload" href="assets/fonts/sora-latin.woff2" as="font" '
                          'type="font/woff2" crossorigin>\n  ')
            extra += '<link rel="stylesheet" href="assets/fonts/fonts.css">\n  '
            text = text.replace(tag, extra + tag, 1)
    return text


def patch_style_css(text: str) -> str:
    return re.sub(r"@import\s+url\([\"']?https://fonts\.googleapis\.com[^)]*\)\s*;\s*\n?", "", text)


def main() -> int:
    parser = argparse.ArgumentParser(description="Self-host Sora font and AOS.")
    parser.add_argument("--source", default=DEFAULT_SOURCE, help="Site folder")
    parser.add_argument("--dry-run", action="store_true", help="Download and check, but don't write anything")
    args = parser.parse_args()

    source = Path(args.source).expanduser().resolve()
    pages = sorted(source.glob("*.html"))
    style = source / "assets" / "css" / "style.css"
    if not pages or not style.exists():
        print(f"Error: {source} doesn't look like the site folder.", file=sys.stderr)
        return 1

    print("Downloading (nothing is written until all downloads succeed)...")
    font_css = fetch(FONT_CSS_URL).decode("utf-8")
    font_files, local_css = build_local_fonts(font_css)
    aos = {name: fetch(url) for name, url in AOS_FILES.items()}

    if b"AOS" not in aos["aos.js"] or b"aos" not in aos["aos.css"].lower():
        raise SystemExit("The AOS files don't look right. Nothing was changed.")

    print(f"  fonts: {', '.join(font_files)}")
    print(f"  AOS {AOS_VERSION}: {', '.join(aos)}")

    if args.dry_run:
        print("\nDry run: nothing written.")
        return 0

    fonts_dir = source / "assets" / "fonts"
    aos_dir = source / "assets" / "vendor" / "aos"
    fonts_dir.mkdir(parents=True, exist_ok=True)
    aos_dir.mkdir(parents=True, exist_ok=True)

    for name, data in font_files.items():
        (fonts_dir / name).write_bytes(data)
    (fonts_dir / "fonts.css").write_text(local_css, encoding="utf-8")
    for name, data in aos.items():
        (aos_dir / name).write_bytes(data)

    for page in pages:
        old = page.read_text(encoding="utf-8")
        new = patch_html(old, "sora-latin.woff2" in font_files)
        if new != old:
            page.write_text(new, encoding="utf-8")
            print(f"  updated {page.name}")

    old = style.read_text(encoding="utf-8")
    new = patch_style_css(old)
    if new != old:
        style.write_text(new, encoding="utf-8")
        print("  updated assets/css/style.css (removed Google Fonts @import)")

    print("\nDone. The site no longer loads anything from Google Fonts or jsDelivr.")
    print("Open each page in a browser to check the font and scroll animations, then commit.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
